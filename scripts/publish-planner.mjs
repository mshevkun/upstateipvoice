import { access, cp, mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';

async function exists(dir) {
  try {
    await access(dir);
    return true;
  }
  catch {
    return false;
  }
}
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(root, 'planner', 'dist');
const htmlSrc = path.join(dist, 'planner', 'dev.html');
const htmlDest = path.join(root, 'planner', 'index.html');
const bundleDest = path.join(root, 'planner', 'assets');
const staticDest = path.join(root, 'assets');
const publicAssets = path.join(root, 'planner', 'public', 'assets');

const html = await readFile(htmlSrc, 'utf8');
if (!html.includes('/planner/assets/')) {
  throw new Error('Planner build did not emit /planner/assets URLs. Check vite base.');
}

const plannerAssetNames = new Set(await readdir(publicAssets));
if (await exists(staticDest)) {
  const existing = await readdir(staticDest);
  const foreign = existing.filter((name) => !plannerAssetNames.has(name) && name !== '.DS_Store');
  if (foreign.length)
    throw new Error('Refusing to rm /assets: contains non-planner files: ' + foreign.join(', '));
}

await rm(bundleDest, { recursive: true, force: true });
await mkdir(bundleDest, { recursive: true });

for (const name of await readdir(path.join(dist, 'assets'))) {
  if (!/\.(js|css|map|ttf|ico)$/.test(name) && !name.startsWith('favicon-'))
    continue;
  await cp(path.join(dist, 'assets', name), path.join(bundleDest, name));
}

await rm(staticDest, { recursive: true, force: true });
await cp(publicAssets, staticDest, { recursive: true });

await writeFile(
  htmlDest,
  '<!-- generated by scripts/publish-planner.mjs from planner/dev.html; do not edit -->\n' + html,
);

const bundles = (await readdir(bundleDest)).filter((name) => name.endsWith('.js') || name.endsWith('.css'));
if (!bundles.length)
  throw new Error('Planner publish copied no JS/CSS bundles.');

console.log('Published planner/index.html with', bundles.length, 'bundles and static /assets.');
