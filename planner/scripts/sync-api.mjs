#!/usr/bin/env node
/** Write sms-portal Practice Architect allowlist + prompt from planner source. */
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const srcDir = path.join(root, 'planner/src');
const apiDir = path.resolve(root, '../upstateipv/sms-portal/api/src/services/practiceArchitect');
const stampDir = path.join(root, 'planner/eval');

function sha(text) {
  return createHash('sha256').update(text).digest('hex');
}

function transpile(rel) {
  let out = ts.transpile(fs.readFileSync(path.join(srcDir, rel + '.ts'), 'utf8'), {
    target: ts.ScriptTarget.ES2022,
    module: ts.ModuleKind.ESNext
  });
  out = out.replace(/from ['"](\.\.?\/[^'"]+)['"]/g, "from '$1.mjs'");
  return out;
}

const fieldsSrc = fs.readFileSync(path.join(srcDir, 'architect/fields.ts'), 'utf8');
const promptSrc = fs.readFileSync(path.join(srcDir, 'architect/prompt.ts'), 'utf8');
const schemaSrc = fs.readFileSync(path.join(srcDir, 'architect/schema.ts'), 'utf8');
const advisorSrc = fs.readFileSync(path.join(srcDir, 'advisor.ts'), 'utf8');
const sourceHash = sha(fieldsSrc + '\n' + promptSrc + '\n' + schemaSrc);

const buildDir = path.join(root, 'planner/.eval-build');
fs.mkdirSync(path.join(buildDir, 'architect'), { recursive: true });
for (const name of [
  'config', 'policy', 'locations', 'routing', 'flow', 'team-state', 'state',
  'architect/schema', 'architect/fields', 'architect/parse', 'architect/extract',
  'architect/ack', 'architect/merge'
]) {
  const dest = path.join(buildDir, name + '.mjs');
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, transpile(name));
}

const fieldsMod = await import(path.join(buildDir, 'architect/fields.mjs'));
const schemaMod = await import(path.join(buildDir, 'architect/schema.mjs'));
const promptMatch = promptSrc.match(/export const INTERPRETER_SYSTEM_PROMPT = `([\s\S]*?)`;/);
if (!promptMatch)
  throw new Error('INTERPRETER_SYSTEM_PROMPT not found');
const promptText = promptMatch[1];

const allowed = fieldsMod.allowedFieldIds();
const blocked = [...fieldsMod.BLOCKED_FIELD_IDS];
const catalog = fieldsMod.catalog();
const compact = catalog.filter(f => !/^hours\.(Saturday|Sunday)\./.test(f.id)).map(f => {
  const row = { id: f.id, type: f.type };
  if (f.enum)
    row.enum = f.enum;
  return row;
});

const header = `/** Generated by planner/scripts/sync-api.mjs. Do not edit by hand. SOURCE_HASH=${sourceHash} */\n`;

const fieldsJs = header + `export const SOURCE_HASH = ${JSON.stringify(sourceHash)};
export const BLOCKED_FIELD_IDS = new Set(${JSON.stringify(blocked, null, 2)});
export const ALLOWED_FIELD_IDS = new Set(${JSON.stringify(allowed, null, 2)});
export const INTENTS = new Set([
  'provide_information',
  'ask_question',
  'skip_current',
  'correct_information',
  'generate_draft',
  'restart',
]);
export const OPERATIONS = new Set(['set', 'skip', 'uncertain', 'clear']);
export function isWritableField(fieldId) {
  if (!fieldId || typeof fieldId !== 'string') return false;
  if (BLOCKED_FIELD_IDS.has(fieldId)) return false;
  if (/sip|extension|dialplan|e911|baa|verified/i.test(fieldId) && !ALLOWED_FIELD_IDS.has(fieldId))
    return false;
  return ALLOWED_FIELD_IDS.has(fieldId);
}
export function compactRegistry() {
  return ${JSON.stringify(compact, null, 2)};
}
`;

const promptJs = header + `export const SOURCE_HASH = ${JSON.stringify(sourceHash)};
export const INTERPRETER_SYSTEM_PROMPT = ${JSON.stringify(promptText)};
export const interpreterResponseSchema = ${JSON.stringify(schemaMod.interpreterResponseSchema, null, 2)};
`;

const fpMatch = advisorSrc.match(/export function fingerprint\(p: Plan\) \{[\s\S]*?\n\}/);
if (!fpMatch)
  throw new Error('fingerprint() not found');
const fingerprintJs = header + `export const SOURCE_HASH = ${JSON.stringify(sourceHash)};
export function fingerprint(p) {
  const body = JSON.stringify({
    planId: p.planId,
    revision: p.revision,
    mode: p.mode,
    name: p.name,
    specialty: p.specialty,
    teams: p.teams,
    endpoints: p.endpoints,
    first: p.first,
    reasons: p.reasons,
    busy: p.busy,
    menu: p.menu,
    languages: p.languages,
    hours: p.hours,
    after: p.after,
    urgent: p.urgent,
    followup: p.followup,
    current: p.current,
    confirmed: p.confirmed,
    policy: p.policy,
    locations: p.locations
  });
  let h = 2166136261;
  for (let i = 0; i < body.length; i++) {
    h ^= body.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return ('00000000' + (h >>> 0).toString(16)).slice(-8);
}
export function identity(p) {
  return { planId: p.planId, revision: p.revision, checksum: fingerprint(p) };
}
`;

if (!fs.existsSync(apiDir))
  throw new Error('sms-portal Practice Architect path missing: ' + apiDir);

fs.writeFileSync(path.join(apiDir, 'fields.generated.js'), fieldsJs);
fs.writeFileSync(path.join(apiDir, 'prompt.generated.js'), promptJs);
fs.writeFileSync(path.join(apiDir, 'fingerprint.generated.js'), fingerprintJs);
fs.writeFileSync(path.join(stampDir, 'api-source.hash'), sourceHash + '\n');

const fieldsShim = header + `export {
  SOURCE_HASH,
  BLOCKED_FIELD_IDS,
  ALLOWED_FIELD_IDS,
  INTENTS,
  OPERATIONS,
  isWritableField,
  compactRegistry,
} from './fields.generated.js';
`;
const promptShim = header + `export { SOURCE_HASH, INTERPRETER_SYSTEM_PROMPT, interpreterResponseSchema } from './prompt.generated.js';
`;
fs.writeFileSync(path.join(apiDir, 'fields.js'), fieldsShim);
fs.writeFileSync(path.join(apiDir, 'prompt.js'), promptShim);

console.log(JSON.stringify({
  sourceHash,
  allowed: allowed.length,
  compact: compact.length,
  apiDir
}, null, 2));
